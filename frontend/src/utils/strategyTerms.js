export function strategyStatusText(status) {
  return STATUS_LABELS[status] || localizeStrategyText(status) || '未知状态'
}

export function localizeStrategyText(value) {
  return TERM_REPLACEMENTS.reduce(
    (text, [pattern, replacement]) => text.replace(pattern, replacement),
    String(value ?? ''),
  )
}
